# Regenerates Data.gs from the Python inputs: the 77 tiered Bonia SKUs
# (scripts/sheet26.csv) and Bonia unit costs (scripts/unitcost.json).
# Run from the repo root: python3 restock-bot/tools/make_data.py
import csv, json
tiers = [[r['sku'], r['tier']] for r in csv.DictReader(open('scripts/sheet26.csv', encoding='utf-8'))]
cost = {k: v[0] for k, v in json.load(open('scripts/unitcost.json')).items()}
with open('restock-bot/Data.gs', 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/make_data.py. Do not edit by hand.\n')
    f.write('// Tiers of the 77 Bonia SKUs from the Bonia Restock Monitor (26 Oct 2026).\n')
    f.write('var BONIA_TIERS = ' + json.dumps(tiers) + ';\n')
    f.write('// Latest Bonia unit cost (RM) from stock report.pdf, 1 Jan - 27 Oct 2026.\n')
    f.write('var UNIT_COST = ' + json.dumps(cost, separators=(',', ':')) + ';\n')
print(len(tiers), 'tiers,', len(cost), 'costs')
